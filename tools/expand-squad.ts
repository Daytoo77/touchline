/**
 * Expand compact scouting files (packages/data/scouting/*.ts) into full club files with explicit
 * attributes (packages/data/src/clubs/*.ts). Existing club files are NOT overwritten unless --force,
 * because they are the hand-editable source of truth once generated.
 *
 *   npm run squads:expand              # generate missing club files, refresh the index
 *   npm run squads:expand -- --force   # regenerate everything (loses hand edits!)
 *   npm run squads:expand -- real-madrid --force
 */
import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { Club as ClubZ, DEFAULT_INSTRUCTIONS, type Club, type Player } from '@touchline/shared';
import { fromTuple, generatePlayer } from '../packages/data/src/gen';
import type { ScoutClub } from '../packages/data/src/scout';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const scoutDir = join(root, 'packages/data/scouting');
const clubDir = join(root, 'packages/data/src/clubs');
const args = process.argv.slice(2);
const force = args.includes('--force');
const only = args.filter((a) => !a.startsWith('--'));

function obj(o: Record<string, number>): string {
  return `{ ${Object.entries(o)
    .map(([k, v]) => `${k}: ${v}`)
    .join(', ')} }`;
}

function playerTs(p: Player): string {
  const head = [
    `id: '${p.id}'`,
    `name: ${JSON.stringify(p.name)}`,
    p.shortName ? `shortName: ${JSON.stringify(p.shortName)}` : null,
    `number: ${p.number}`,
    `age: ${p.age}`,
    `nationality: '${p.nationality}'`,
    `positions: [${p.positions.map((x) => `'${x}'`).join(', ')}]`,
    `foot: '${p.foot}'`,
  ]
    .filter(Boolean)
    .join(', ');
  const lines = [
    `    {`,
    `      ${head},`,
    `      technical: ${obj(p.technical)},`,
    `      mental: ${obj(p.mental)},`,
    `      physical: ${obj(p.physical)},`,
  ];
  if (p.goalkeeping) lines.push(`      goalkeeping: ${obj(p.goalkeeping)},`);
  if (p.flag) lines.push(`      flag: ${JSON.stringify(p.flag)},`);
  lines.push(`    },`);
  return lines.join('\n');
}

function clubTs(c: Club, from: string): string {
  return `// ${c.name}: 2026-27 squad. Ratings are Touchline's own estimates from each player's level and role
// (not taken from any game or ratings database). Generated from packages/data/scouting/${from};
// this file is now the source of truth: edit any number by hand (1-20), then run \`npm run data:check\`.
import { defineClub } from '../define';

export default defineClub({
  id: '${c.id}',
  name: ${JSON.stringify(c.name)},
  shortName: ${JSON.stringify(c.shortName)},
  abbr: '${c.abbr}',
  country: '${c.country}',
  pot: ${c.pot},
  kits: {
    home: ${JSON.stringify(c.kits.home)},
    away: ${JSON.stringify(c.kits.away)},
    gk: ${JSON.stringify(c.kits.gk)},
  },
  defaultTactic: { formation: '${c.defaultTactic.formation}', instructions: ${JSON.stringify(c.defaultTactic.instructions)} },
  dataAsOf: '${c.dataAsOf}',${c.notes ? `\n  notes: ${JSON.stringify(c.notes)},` : ''}
  players: [
${c.players.map(playerTs).join('\n')}
  ],
});
`;
}

function camel(id: string): string {
  return id.replace(/-([a-z0-9])/g, (_, ch: string) => ch.toUpperCase()).replace(/^([0-9])/, '_$1');
}

async function main(): Promise<void> {
  const files = readdirSync(scoutDir).filter((f) => f.endsWith('.ts'));
  let wrote = 0;
  for (const f of files) {
    const id = f.replace(/\.ts$/, '');
    if (only.length && !only.includes(id)) continue;
    const target = join(clubDir, `${id}.ts`);
    if (existsSync(target) && !force) continue;
    const mod = (await import(pathToFileURL(join(scoutDir, f)).href)) as { default: ScoutClub };
    const s = mod.default;
    const club: Club = {
      id: s.id,
      name: s.name,
      shortName: s.shortName,
      abbr: s.abbr,
      country: s.country,
      pot: s.pot,
      kits: s.kits,
      defaultTactic: { formation: s.formation, instructions: { ...DEFAULT_INSTRUCTIONS, ...s.instructions } },
      dataAsOf: '2026-11-03',
      ...(s.notes ? { notes: s.notes } : {}),
      players: s.players.map((t) => generatePlayer(s.prefix, fromTuple(t))),
    };
    const parsed = ClubZ.safeParse(club);
    if (!parsed.success) {
      console.error(`✗ ${id}:`, parsed.error.issues.map((i) => i.message).join('; '));
      process.exitCode = 1;
      continue;
    }
    writeFileSync(target, clubTs(club, f));
    wrote++;
    console.log(`✓ ${id} (${club.players.length} players)`);
  }
  // Rebuild the index from whatever club files exist.
  const clubs = readdirSync(clubDir)
    .filter((f) => f.endsWith('.ts') && f !== 'index.ts')
    .map((f) => f.replace(/\.ts$/, ''))
    .sort();
  const index = `// Generated by tools/expand-squad.ts: lists every club file in this folder.
import type { Club } from '@touchline/shared';
${clubs.map((c) => `import ${camel(c)} from './${c}';`).join('\n')}

export const CLUB_LIST: Club[] = [${clubs.map(camel).join(', ')}];
`;
  writeFileSync(join(clubDir, 'index.ts'), index);
  console.log(`${wrote} club file(s) written; index lists ${clubs.length}.`);
}

main();
